# Import required libraries

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Machine Learning libraries
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    ConfusionMatrixDisplay
)

import warnings
warnings.filterwarnings('ignore')

print("Libraries imported successfully!")

# Download hotel booking dataset

url = "https://raw.githubusercontent.com/rfordatascience/tidytuesday/master/data/2020/2020-02-11/hotels.csv"

df = pd.read_csv(url)

print("Dataset loaded successfully!")

# Display first 5 rows

df.head()

# Number of rows and columns

print("Number of rows:", df.shape[0])
print("Number of columns:", df.shape[1])

# Display all column names

print(df.columns.tolist())

# Dataset information

df.info()

# Check missing values

missing_values = df.isnull().sum()

print(missing_values[missing_values > 0])

# Statistical summary of numerical variables

df.describe()

# Select important columns

selected_columns = [
    'is_canceled',
    'lead_time',
    'arrival_date_month',
    'arrival_date_week_number',
    'stays_in_weekend_nights',
    'stays_in_week_nights',
    'adults',
    'children',
    'babies',
    'is_repeated_guest',
    'previous_cancellations',
    'previous_bookings_not_canceled',
    'booking_changes',
    'deposit_type',
    'customer_type',
    'adr',
    'market_segment',
    'distribution_channel',
    'hotel'
]

data = df[selected_columns].copy()

data.head()

# Check missing values in selected data

data.isnull().sum()

# Check missing values in selected data

data.isnull().sum()

# Fill missing values

data['children'] = data['children'].fillna(0)

# Fill categorical missing values
data['market_segment'] = data['market_segment'].fillna('Unknown')
data['distribution_channel'] = data['distribution_channel'].fillna('Unknown')

print("Missing values handled successfully!")

# Count cancelled and non-cancelled bookings

print(data['is_canceled'].value_counts())

sns.countplot(x='is_canceled', data=data)

plt.title("Hotel Booking Cancellation Distribution")
plt.xlabel("Booking Cancelled (0 = No, 1 = Yes)")
plt.ylabel("Number of Bookings")
plt.show()

# Calculate cancellation percentage

cancellation_rate = data['is_canceled'].mean() * 100

print(f"Overall cancellation rate: {cancellation_rate:.2f}%")

plt.figure(figsize=(8,5))

sns.boxplot(
    x='is_canceled',
    y='lead_time',
    data=data
)

plt.title("Lead Time vs Booking Cancellation")
plt.xlabel("Cancelled (0 = No, 1 = Yes)")
plt.ylabel("Lead Time")
plt.show()

plt.figure(figsize=(8,5))

sns.countplot(
    x='deposit_type',
    hue='is_canceled',
    data=data
)

plt.title("Cancellation by Deposit Type")
plt.xlabel("Deposit Type")
plt.ylabel("Number of Bookings")
plt.xticks(rotation=30)
plt.show()

plt.figure(figsize=(8,5))

sns.countplot(
    x='customer_type',
    hue='is_canceled',
    data=data
)

plt.title("Cancellation by Customer Type")
plt.xlabel("Customer Type")
plt.ylabel("Number of Bookings")
plt.xticks(rotation=30)
plt.show()

# Select numerical columns

numeric_data = data.select_dtypes(include=np.number)

plt.figure(figsize=(12,8))

sns.heatmap(
    numeric_data.corr(),
    annot=True,
    cmap='coolwarm',
    fmt='.2f'
)

plt.title("Correlation Heatmap")
plt.show()

# Separate independent variables and target variable

X = data.drop('is_canceled', axis=1)
y = data['is_canceled']

print("Features:", X.shape)
print("Target:", y.shape)

# Convert categorical variables into numerical variables

X = pd.get_dummies(X, drop_first=True)

print("After encoding:")
print(X.shape)

X.head()

# Split dataset into training and testing sets

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

# Feature scaling

scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

print("Feature scaling completed!")

# Create Logistic Regression model

model = LogisticRegression(
    max_iter=1000,
    random_state=42
)

# Train the model
model.fit(X_train_scaled, y_train)

print("Logistic Regression model trained successfully!")

# Predict cancellation

y_pred = model.predict(X_test_scaled)

print("Predictions completed!")
print(y_pred[:20])

# Calculate accuracy

accuracy = accuracy_score(y_test, y_pred)

print(f"Model Accuracy: {accuracy * 100:.2f}%")

# Classification report

print(classification_report(y_test, y_pred))

# Confusion Matrix

cm = confusion_matrix(y_test, y_pred)

disp = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=['Not Cancelled', 'Cancelled']
)

disp.plot()

plt.title("Confusion Matrix")
plt.show()

# Get feature importance from Logistic Regression coefficients

feature_names = X.columns

coefficients = model.coef_[0]

importance_df = pd.DataFrame({
    'Feature': feature_names,
    'Coefficient': coefficients
})

# Sort by absolute coefficient
importance_df['Absolute_Coefficient'] = abs(
    importance_df['Coefficient']
)

importance_df = importance_df.sort_values(
    by='Absolute_Coefficient',
    ascending=False
)

importance_df.head(15)

# Plot top 15 important features

top_features = importance_df.head(15)

plt.figure(figsize=(10,6))

sns.barplot(
    x='Absolute_Coefficient',
    y='Feature',
    data=top_features
)

plt.title("Top Features Affecting Booking Cancellation")
plt.xlabel("Absolute Logistic Regression Coefficient")
plt.ylabel("Feature")

plt.show()

# Select one booking from test data

sample_booking = X_test.iloc[[0]]

sample_booking_scaled = scaler.transform(sample_booking)

prediction = model.predict(sample_booking_scaled)[0]

probability = model.predict_proba(sample_booking_scaled)[0][1]

if prediction == 1:
    result = "Booking is likely to be CANCELLED"
else:
    result = "Booking is likely to be NOT CANCELLED"

print(result)
print(f"Cancellation Probability: {probability * 100:.2f}%")

print("==========================================")
print(" HOTEL BOOKING CANCELLATION PREDICTION")
print("==========================================")

print(f"Model Used       : Logistic Regression")
print(f"Training Samples : {len(X_train)}")
print(f"Testing Samples  : {len(X_test)}")
print(f"Accuracy         : {accuracy * 100:.2f}%")

